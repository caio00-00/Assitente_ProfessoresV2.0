import sys
import os
from datetime import date
from sqlalchemy import create_engine, text
from sqlalchemy.orm import sessionmaker
from dotenv import load_dotenv

# Set PYTHONPATH to include current directory
sys.path.append(os.getcwd())

# Load env vars
load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")

try:
    engine = create_engine(DATABASE_URL)
    SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)
    db = SessionLocal()

    # Item 2 & 3: API Call Simulation
    from app.models.class_report import ClassReport
    from app.api.rotas_report import _apply_report_filters

    print("--- ITEM 2 & 3: API SIMULATION ---")
    try:
        q = db.query(ClassReport)
        # Using exact values from user request
        kwargs = {
            "turma_id": "e37f3acb-a739-4f7b-82f8-bb1d38e6aec0",
            "data_inicio": date(2026, 5, 4),
            "data_fim": date(2026, 5, 10)
        }
        q = _apply_report_filters(q, **kwargs)
        total = q.count()
        items = q.limit(200).all()
        
        print(f"Total: {total}")
        print(f"Items count: {len(items)}")
        for item in items:
            print(f"ID: {item.id}, Status: {item.status}, Data: {item.data_aula}")
            
        print("\nSQL Generated by SQLAlchemy:")
        print(q.statement.compile(compile_kwargs={"literal_binds": True}))
        
    except Exception as e:
        print(f"Error simulating API: {e}")

    db.close()
except Exception as e:
    print(f"Fatal error: {e}")
